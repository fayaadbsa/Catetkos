-- Skema Postgres, setara dengan skema SQLite lama. Uang = BIGINT (Rupiah, bisa > 2 miliar), tanggal = TEXT 'YYYY-MM-DD' (sama seperti sebelumnya).
CREATE TABLE users (
  id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  hash     TEXT NOT NULL,
  salt     TEXT NOT NULL
);

CREATE TABLE kos (
  id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL
);

CREATE TABLE memberships (
  user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  kos_id  INTEGER NOT NULL REFERENCES kos (id) ON DELETE CASCADE,
  PRIMARY KEY (user_id, kos_id)
);
CREATE INDEX idx_mem_kos ON memberships (kos_id);

CREATE TABLE room_types (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kos_id     INTEGER NOT NULL REFERENCES kos (id) ON DELETE CASCADE,
  name       TEXT NOT NULL,
  base_price BIGINT NOT NULL CHECK (base_price >= 0),
  capacity   INTEGER NOT NULL DEFAULT 1 CHECK (capacity >= 1),
  archived   INTEGER NOT NULL DEFAULT 0,
  UNIQUE (kos_id, name)
);

CREATE TABLE rooms (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kos_id         INTEGER NOT NULL REFERENCES kos (id) ON DELETE CASCADE,
  number         TEXT NOT NULL,
  room_type_id   INTEGER NOT NULL REFERENCES room_types (id) ON DELETE RESTRICT,
  price_override BIGINT CHECK (price_override IS NULL OR price_override >= 0),
  archived       INTEGER NOT NULL DEFAULT 0,
  UNIQUE (kos_id, number)
);
CREATE INDEX idx_rooms_kos ON rooms (kos_id);

CREATE TABLE promos (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         TEXT NOT NULL,
  room_type_id INTEGER REFERENCES room_types (id) ON DELETE CASCADE,
  price        BIGINT NOT NULL CHECK (price >= 0),
  start_date   TEXT NOT NULL,
  end_date     TEXT NOT NULL,
  kos_id       INTEGER NOT NULL REFERENCES kos (id) ON DELETE CASCADE,
  CHECK (end_date >= start_date)
);

CREATE TABLE guests (
  id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name   TEXT NOT NULL,
  phone  TEXT,
  note   TEXT,
  kos_id INTEGER NOT NULL REFERENCES kos (id) ON DELETE CASCADE
);

CREATE TABLE bookings (
  id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id               INTEGER NOT NULL REFERENCES rooms (id) ON DELETE RESTRICT,
  guest_id              INTEGER NOT NULL REFERENCES guests (id) ON DELETE RESTRICT,
  promo_id              INTEGER REFERENCES promos (id) ON DELETE SET NULL,
  check_in              TEXT NOT NULL,
  check_out             TEXT NOT NULL,
  price_total           BIGINT NOT NULL CHECK (price_total >= 0),
  status                TEXT NOT NULL DEFAULT 'booked' CHECK (status IN ('booked', 'checked_in', 'checked_out', 'cancelled')),
  note                  TEXT,
  deposit               BIGINT NOT NULL DEFAULT 0 CHECK (deposit >= 0),
  deposit_paid_date     TEXT,
  deposit_returned_date TEXT,
  kos_id                INTEGER NOT NULL REFERENCES kos (id) ON DELETE CASCADE,
  CHECK (check_out > check_in)
);
CREATE INDEX idx_bookings_room ON bookings (room_id, check_in);
CREATE INDEX idx_bookings_kos ON bookings (kos_id);

CREATE TABLE categories (
  id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kos_id INTEGER NOT NULL REFERENCES kos (id) ON DELETE CASCADE,
  kind   TEXT NOT NULL CHECK (kind IN ('income', 'expense', 'capital')),
  name   TEXT NOT NULL,
  UNIQUE (kos_id, kind, name)
);

CREATE TABLE transactions (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id INTEGER NOT NULL REFERENCES categories (id) ON DELETE RESTRICT,
  booking_id  INTEGER REFERENCES bookings (id) ON DELETE RESTRICT,
  room_id     INTEGER REFERENCES rooms (id) ON DELETE SET NULL,
  date        TEXT NOT NULL,
  amount      BIGINT NOT NULL CHECK (amount > 0),
  method      TEXT,
  note        TEXT,
  kos_id      INTEGER NOT NULL REFERENCES kos (id) ON DELETE CASCADE
);
CREATE INDEX idx_tx_date ON transactions (date);
CREATE INDEX idx_tx_booking ON transactions (booking_id);
CREATE INDEX idx_tx_kos ON transactions (kos_id, date);
